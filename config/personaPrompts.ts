  /** 누구인가 (현실의 배경 + GM을 맡은 이유) */
  identity: string;
  /** 성격 */
  personality: string;
  /** 말투 규칙 */
  speech: string;
  /** 진행·판정 성향 (난이도, 힌트량, 피해 정도) */
